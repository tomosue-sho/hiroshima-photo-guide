class Command(BaseCommand):

    help = "ダム湖百選65湖の初期データを登録・更新します。"

    def handle(self, *args, **options):

        created_count = 0
        updated_count = 0

        for (
            order,
            name,
            dam_name,
            prefecture,
            slug,
            latitude,
            longitude,
        ) in DAM_LAKES:

            lake, created = DamLake.objects.update_or_create(
                slug=slug,
                defaults={
                    "name": name,
                    "dam_name": dam_name,
                    "prefecture": prefecture,
                    "order": order,
                    "latitude": latitude,
                    "longitude": longitude,
                },
            )

            if created:
                created_count += 1

                self.stdout.write(
                    self.style.SUCCESS(
                        f"Created: {order:02d} {name}"
                    )
                )

            else:
                updated_count += 1

                self.stdout.write(
                    f"Updated: {order:02d} {name}"
                )

        self.stdout.write("")

        self.stdout.write(
            self.style.SUCCESS(
                f"完了: 新規 {created_count} 件 / 更新 {updated_count} 件"
            )
        )